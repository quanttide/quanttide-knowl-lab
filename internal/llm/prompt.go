package llm

var prompts = map[string]string{
	"default": `你是一位知识发现专家。请分析以下文本片段，提取其中蕴含的语义三元组（事实陈述），并为每条三元组评估认知密度。

## 评估标准

- **新颖性**：信息是否非显而易见（0.0~1.0）
- **领域特异性**：信息是否只在该领域成立（0.0~1.0）
- **反直觉程度**：信息是否与常识相悖（0.0~1.0）

认知密度 = (新颖性 + 领域特异性 + 反直觉程度) / 3

## 输出格式

返回 JSON 对象，格式如下：
{
  "triples": [
    {
      "subject": "主语",
      "predicate": "谓语",
      "object": "宾语",
      "novelty": 0.0~1.0,
      "domain_specificity": 0.0~1.0,
      "counter_intuitive": 0.0~1.0,
      "confidence": 0.0~1.0,
      "sentence": "原文中出现该事实的句子"
    }
  ]
}

## 规则

1. 只提取文本中明确陈述的事实，不要编造
2. 如果文本不含任何事实，返回 {"triples": []}
3. confidence 基于认知密度计算，但考虑文本明确程度
4. 每条三元组必须来自原文中的具体句子
5. 最多提取 10 条最相关的事实
6. **使用多样化的谓语**：避免全部用"是"。优先使用文本中具体的动词或关系词作为谓语

文本片段：
`,

	"fiction": `你是一位文学分析专家。请分析以下小说片段，提取其中蕴含的语义三元组，重点关注人物关系、情感变化、情节发展和场景设定。

## 输出格式

返回 JSON 对象，格式如下：
{
  "triples": [
    {
      "subject": "主语",
      "predicate": "谓语",
      "object": "宾语",
      "novelty": 0.0~1.0,
      "domain_specificity": 0.0~1.0,
      "counter_intuitive": 0.0~1.0,
      "confidence": 0.0~1.0,
      "sentence": "原文中出现该事实的句子"
    }
  ]
}

## 规则

1. 只提取与情节、人物、情感、场景相关的关键事实，忽略冗余的日常细节
2. 聚焦核心关系：人物之间的情感互动（暗恋、想念、吐槽、安慰等）
3. 聚焦关键情节转折：重要决定、意外相遇、关系变化
4. 聚焦人物状态：情绪变化、内心活动、性格特质
5. 如果片段不含文学性关键信息，返回 {"triples": []}
6. **使用多样化的谓语**：偏好具体动词如"暗恋"、"想念"、"吐槽"、"安慰"、"邀请"等

文本片段：
`,

	"technical": `你是一位技术文档分析专家。请分析以下文本片段，提取其中蕴含的语义三元组，重点关注技术决策、工程经验、架构关系和开发方法论。

## 输出格式

返回 JSON 对象，格式如下：
{
  "triples": [
    {
      "subject": "主语",
      "predicate": "谓语",
      "object": "宾语",
      "novelty": 0.0~1.0,
      "domain_specificity": 0.0~1.0,
      "counter_intuitive": 0.0~1.0,
      "confidence": 0.0~1.0,
      "sentence": "原文中出现该事实的句子"
    }
  ]
}

## 规则

1. 只提取与技术决策、工程经验、架构设计、开发方法论相关的陈述，忽略个人情绪
2. 聚焦因果关系：A 导致 B、A 是因为 B、A 解决了 B
3. 聚焦对比关系：A 比 B 更好、A 不同于 B
4. 聚焦决策理由：选择 A 而不是 B 的原因是 C
5. 聚焦经验教训：A 方法有效、A 方法不可行、A 的前提是 B
6. 如果片段不含技术性关键信息，返回 {"triples": []}
7. **使用多样化的谓语**：偏好具体动词如"导致"、"解决"、"对比"、"选择"、"依赖"等

文本片段：
`,
}

func AssessmentPrompt() string { return prompts["default"] }

func GetPrompt(domain string) string {
	if p, ok := prompts[domain]; ok {
		return p
	}
	return prompts["default"]
}
